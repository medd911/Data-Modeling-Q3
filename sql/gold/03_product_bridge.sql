-- Product dimension and bridge. A payment can list up to 5 products, so payment -> product
-- is many-to-many. Run after 02_transform_and_load.sql.
--
--   gold.dim_product             one row per distinct product
--   gold.bridge_payment_product  one row per (payment, product), with product_share = 1 / products on the payment
--
-- To total by product, sum the amount times the share, so no payment is counted twice:
--     sum(f.total_payment_us_dollars * b.product_share)

SET work_mem = '512MB';

DROP TABLE IF EXISTS gold.bridge_payment_product;
DROP TABLE IF EXISTS gold.dim_product;

CREATE TABLE gold.dim_product (
    product_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_bk        char(32) NOT NULL UNIQUE,    -- md5 of the attributes below
    product_name      text,
    product_type      text,                         -- Drug / Biological / Device / Medical Supply
    product_category  text,                         -- therapeutic area
    ndc               text,
    pdi               text
);

-- One row per payment and product slot that has a product
CREATE TEMP TABLE tmp_product_slots AS
SELECT s.record_id,
       v.slot,
       v.product_name, v.product_type, v.product_category, v.ndc, v.pdi,
       md5(lower(concat_ws('|', v.product_name, coalesce(v.product_type,''), coalesce(v.product_category,''),
                                 coalesce(v.ndc,''), coalesce(v.pdi,'')))) AS product_bk
FROM gold.stg_general s
CROSS JOIN LATERAL (VALUES
    (1, s.marketed_name_of_product_1, s.type_of_product_1, s.product_category_1, s.ndc_of_product_1, s.pdi_of_product_1),
    (2, s.marketed_name_of_product_2, s.type_of_product_2, s.product_category_2, s.ndc_of_product_2, s.pdi_of_product_2),
    (3, s.marketed_name_of_product_3, s.type_of_product_3, s.product_category_3, s.ndc_of_product_3, s.pdi_of_product_3),
    (4, s.marketed_name_of_product_4, s.type_of_product_4, s.product_category_4, s.ndc_of_product_4, s.pdi_of_product_4),
    (5, s.marketed_name_of_product_5, s.type_of_product_5, s.product_category_5, s.ndc_of_product_5, s.pdi_of_product_5)
) AS v(slot, product_name, product_type, product_category, ndc, pdi)
WHERE v.product_name IS NOT NULL;

-- placeholder for payments with no product
INSERT INTO gold.dim_product (product_key, product_bk, product_name)
VALUES (-1, repeat('0', 32), 'No Related Product / Unknown');

INSERT INTO gold.dim_product (product_bk, product_name, product_type, product_category, ndc, pdi)
SELECT DISTINCT ON (product_bk) product_bk, product_name, product_type, product_category, ndc, pdi
FROM tmp_product_slots
ORDER BY product_bk;

ANALYZE gold.dim_product;

CREATE TABLE gold.bridge_payment_product (
    payment_key    bigint   NOT NULL REFERENCES gold.fct_payments (payment_key),
    product_slot   smallint NOT NULL,               -- 1..5, 0 = payment with no product
    product_key    bigint   NOT NULL REFERENCES gold.dim_product (product_key),
    product_share  numeric(9,8) NOT NULL,           -- 1 / products on the payment
    PRIMARY KEY (payment_key, product_slot)
);

INSERT INTO gold.bridge_payment_product (payment_key, product_slot, product_key, product_share)
SELECT f.payment_key, t.slot, p.product_key,
       1.0 / count(*) OVER (PARTITION BY t.record_id)
FROM tmp_product_slots t
JOIN gold.fct_payments f ON f.record_id  = t.record_id
JOIN gold.dim_product  p ON p.product_bk = t.product_bk;

-- payments with no product get one row so totals still add up
INSERT INTO gold.bridge_payment_product (payment_key, product_slot, product_key, product_share)
SELECT f.payment_key, 0, -1, 1
FROM gold.fct_payments f
WHERE NOT EXISTS (SELECT 1 FROM gold.bridge_payment_product b WHERE b.payment_key = f.payment_key);

CREATE INDEX ix_bridge_product ON gold.bridge_payment_product (product_key);
ANALYZE gold.bridge_payment_product;

DROP TABLE tmp_product_slots;
