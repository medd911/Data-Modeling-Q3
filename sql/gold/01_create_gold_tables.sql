-- Gold layer star schema for CMS Open Payments (General Payments), PostgreSQL 16.
--
--   fact       fct_payments               one row per published payment record (Record_ID)
--   dimensions dim_date, dim_recipient, dim_teaching_hospital, dim_manufacturer,
--              dim_product, dim_travel, dim_payment_form, dim_payment_nature, dim_payment_flags
--   lookup     lkp_recipient_type
--   bridge     bridge_payment_product     (created with dim_product in 03_product_bridge.sql)
--
-- Every foreign key on the fact is NOT NULL. A missing value points to a placeholder row:
--   date, manufacturer, recipient, teaching hospital: key -1 = Unknown, -2 = Not applicable
--   (a hospital payment has no physician, and a physician payment has no hospital)
--   travel, flags, nature, form, recipient type: an 'N/A' / 'Unknown' row loaded from the data

CREATE SCHEMA IF NOT EXISTS gold;

DROP TABLE IF EXISTS gold.bridge_payment_product CASCADE;
DROP TABLE IF EXISTS gold.dim_product            CASCADE;
DROP TABLE IF EXISTS gold.fct_payments           CASCADE;
DROP TABLE IF EXISTS gold.dim_recipient          CASCADE;
DROP TABLE IF EXISTS gold.dim_teaching_hospital  CASCADE;
DROP TABLE IF EXISTS gold.dim_manufacturer       CASCADE;
DROP TABLE IF EXISTS gold.dim_travel             CASCADE;
DROP TABLE IF EXISTS gold.dim_payment_form       CASCADE;
DROP TABLE IF EXISTS gold.dim_payment_nature     CASCADE;
DROP TABLE IF EXISTS gold.dim_payment_flags      CASCADE;
DROP TABLE IF EXISTS gold.lkp_recipient_type     CASCADE;
DROP TABLE IF EXISTS gold.dim_date               CASCADE;


-- Dimensions -----------------------------------------------------------------

CREATE TABLE gold.dim_date (
    date_key        integer PRIMARY KEY,          -- YYYYMMDD, -1 = unknown
    full_date       date,
    day_of_month    smallint,
    month_number    smallint,
    month_name      text,
    month_short     text,
    quarter_number  smallint,
    quarter_name    text,
    year_number     smallint,
    year_month      text,
    year_quarter    text,
    day_of_week     smallint,
    day_name        text,
    week_of_year    smallint,
    is_weekend      boolean
);

-- Physicians and non-physician practitioners
CREATE TABLE gold.dim_recipient (
    recipient_key         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_profile_id  bigint UNIQUE,           -- business key
    recipient_npi         bigint,
    first_name            text,
    middle_name           text,
    last_name             text,
    name_suffix           text,
    full_name             text,
    recipient_type        text,
    primary_type          text,
    specialty             text,
    license_state         text,
    address_line1         text,
    address_line2         text,
    city                  text,
    state_code            text,
    zip_code              text,
    country               text,
    province              text,
    postal_code           text
);

CREATE TABLE gold.dim_teaching_hospital (
    teaching_hospital_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teaching_hospital_id   bigint UNIQUE,          -- business key
    hospital_name          text,
    hospital_ccn           text,
    address_line1          text,
    city                   text,
    state_code             text,
    zip_code               text
);

CREATE TABLE gold.dim_manufacturer (
    manufacturer_key              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_id               text UNIQUE,     -- business key
    manufacturer_name             text,
    submitting_manufacturer_name  text,
    manufacturer_state            text,
    manufacturer_country          text
);

CREATE TABLE gold.dim_travel (
    travel_key      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    travel_city     text,
    travel_state    text,
    travel_country  text,
    UNIQUE (travel_city, travel_state, travel_country)
);

CREATE TABLE gold.dim_payment_form (
    payment_form_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_form      text UNIQUE
);

CREATE TABLE gold.dim_payment_nature (
    payment_nature_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_nature      text UNIQUE
);

-- Junk dimension: the low-cardinality Yes/No indicator columns, one row per combination
CREATE TABLE gold.dim_payment_flags (
    payment_flags_key          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_type                text,
    physician_ownership        text,
    third_party_payment        text,
    charity                    text,
    third_party_is_recipient   text,
    delay_in_publication       text,
    dispute_status             text,
    related_product            text,
    UNIQUE (change_type, physician_ownership, third_party_payment, charity,
            third_party_is_recipient, delay_in_publication, dispute_status, related_product)
);

-- Lookup: the recipient type as it was on the payment
CREATE TABLE gold.lkp_recipient_type (
    recipient_type_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_type      text UNIQUE
);


-- Fact -----------------------------------------------------------------------

CREATE TABLE gold.fct_payments (
    payment_key                                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id                                    bigint NOT NULL UNIQUE,   -- degenerate dimension

    date_key                                     integer NOT NULL,
    manufacturer_key                             bigint  NOT NULL,
    recipient_key                                bigint  NOT NULL,
    teaching_hospital_key                        bigint  NOT NULL,
    recipient_type_key                           bigint  NOT NULL,
    payment_nature_key                           bigint  NOT NULL,
    payment_form_key                             bigint  NOT NULL,
    travel_key                                   bigint  NOT NULL,
    payment_flags_key                            bigint  NOT NULL,

    total_payment_us_dollars                     double precision NOT NULL,
    number_of_payments_included_in_total_amount  bigint NOT NULL
);

-- Foreign keys and indexes on the fact are added at the end of 02_transform_and_load.sql,
-- after the data is loaded (much faster than checking them row by row).
